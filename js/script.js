// 根据作者获取年代信息
function getAuthorEra(author) {
    return authorEraMap[author] || 'unknown';
}

function getAllMarkers() {
    return Object.keys(nanjingCoords).map(locationName => {
        const works = locationToWorks[locationName] || [];
        
        // 修改这里：存储完整的作品对象而不是字符串
        const worksList = works.map(item => ({
            title: item.work.title,
            author: item.author,
            excerpt: item.work.excerpt,
            nanjingDescription: item.work.nanjingDescription,
            location: item.work.location || locationName,
            era: getAuthorEra(item.author) // 添加年代信息
        }));
        
        // 作者去重
        const authors = [...new Set(works.map(item => item.author))];
        
        // 计算主要年代（取出现次数最多的年代）
        const eraCounts = {};
        worksList.forEach(work => {
            if (work.era && work.era !== 'unknown') {
                eraCounts[work.era] = (eraCounts[work.era] || 0) + 1;
            }
        });
        
        let mainEra = 'unknown';
        let maxCount = 0;
        Object.keys(eraCounts).forEach(era => {
            if (eraCounts[era] > maxCount) {
                maxCount = eraCounts[era];
                mainEra = era;
            }
        });

        return {
            name: locationName,
            value: nanjingCoords[locationName],
            excerpt: locationDescriptions[locationName] || '南京文学地标',
            works: worksList, // 存储对象数组而不是字符串
            authors: authors,
            era: mainEra, // 添加主要年代信息
            symbol: 'pin',
            symbolSize: [40, 50],
            itemStyle: { 
                color: getEraColor(mainEra) // 根据年代设置颜色
            },
            label: {
                show: true,
                formatter: '{b}',
                position: 'bottom',
                color: '#1a3d66',
                fontSize: 12
            }
        };
    });
}

// 根据年代获取颜色
function getEraColor(era) {
    const colorMap = {
        '1920-1930': '#ff6b6b', // 红色
        '1930-1940': '#4ecdc4', // 青色
        '1950-1960': '#45b7d1', // 蓝色
        '1980至今': '#96ceb4',  // 绿色
        'unknown': '#ffd166'    // 黄色
    };
    return colorMap[era] || '#ffd166';
}

